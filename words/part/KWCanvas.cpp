void KWCanvas::mousePressEvent(QMouseEvent *e)
{
    const QPointF documentPoint = m_viewMode->viewToDocument(e->position().toPoint() + m_documentOffset, m_viewConverter);
    if (e->button() == Qt::LeftButton) {
        KoShape *hitShape = shapeManager()->shapeAt(documentPoint, KoFlake::ShapeOnTop);
        const auto selectedShapes = shapeManager()->selection()->selectedShapes(KoFlake::TopLevelSelection);
        const bool objectSelected = std::any_of(selectedShapes.cbegin(), selectedShapes.cend(), [](KoShape *shape) {
            return shape && !dynamic_cast<KoTextShapeData *>(shape->userData());
        });
        const QString activeTool = KoToolManager::instance()->activeToolId();
        const bool drawingToolActive = activeTool == QLatin1String("CreateShapesTool") || activeTool == QLatin1String("KoPencilTool")
            || activeTool == QLatin1String("CreatePathTool") || activeTool == QLatin1String("ConnectionTool");
        // Only standalone text frames (the page body and text boxes) qualify for
        // returning to text editing.  Text shapes living inside a group (chart
        // labels and friends) belong to their parent object, and annotation
        // (comment) shapes are handled as objects.
        const bool hitEditableText = hitShape && !hitShape->parent() && dynamic_cast<KoTextShapeData *>(hitShape->userData())
            && hitShape->shapeId() != QLatin1String("AnnotationTextShapeID");
        // Clicking the body/header/footer text of the page always returns to
        // text editing (Office-like); those auto-generated frames must never
        // end up selected as objects covering the whole page.
        bool hitPageText = false;
        if (hitEditableText) {
            const KWFrame *frame = document()->frameOfShape(hitShape);
            hitPageText = frame && Words::isAutoGenerated(KWFrameSet::from(frame->shape()));
        }
        if (!drawingToolActive && (hitPageText || (objectSelected && hitEditableText))) {
            // Office-like behavior: clicking the text around a selected object
            // returns to text editing at that position.  The text shape has to be
            // selected before the tool switch because the text tool only activates
            // on text shapes taken from the current selection; without that it
            // immediately hands control back and the click would select the page's
            // top-level text frame as an object instead.
            KoSelection *selection = shapeManager()->selection();
            selection->deselectAll();
            selection->select(hitShape);
            KoToolManager::instance()->switchToolRequested(QStringLiteral("TextToolFactory_ID"));
        }
    }
    m_toolProxy->mousePressEvent(e, documentPoint);
}

void KWCanvas::mouseReleaseEvent(QMouseEvent *e)
{
    const bool pictureWasSelected = isPictureShapeSelected();
    // MS Word-like auto shape handling: a plain click on a not-yet-selected auto
    // shape (rectangle, ellipse, ...) should just select it with the shape
    // handling tool; only double-click opens the path editing tool.  Remember
    // the click target beforehand so double-clicks (where the shape is already
    // selected from the first click) keep the path editing tool.
    const QPointF documentPoint = m_viewMode->viewToDocument(e->position().toPoint() + m_documentOffset, m_viewConverter);
    KoShape *hitShape = shapeManager()->shapeAt(documentPoint, KoFlake::ShapeOnTop);
    const bool clickedAutoShapeWasSelected = hitShape && dynamic_cast<KoParameterShape *>(hitShape) && shapeManager()->selection()->isSelected(hitShape);
    const QString toolBeforeRelease = KoToolManager::instance()->activeToolId();
    m_toolProxy->mouseReleaseEvent(e, documentPoint);
    preferShapeHandlingForPictures(pictureWasSelected);
    if (!clickedAutoShapeWasSelected && e->button() == Qt::LeftButton && KoToolManager::instance()->activeToolId() == QLatin1String("PathToolFactoryId")) {
        KoToolManager::instance()->switchToolRequested(KoInteractionTool_ID);
    }
    // After drawing an auto shape the create tool queues a switch to the path
    // editing tool (which also changes the mouse pointer) and hands control
    // back via done().  MS Word-like behavior is to finish in the Select tool
    // instead; queue the switch after the pending one so it wins.
    if (e->button() == Qt::LeftButton && toolBeforeRelease == QLatin1String("CreateShapesTool")) {
        const auto createdShapes = shapeManager()->selection()->selectedShapes(KoFlake::TopLevelSelection);
        if (!createdShapes.isEmpty() && dynamic_cast<KoParameterShape *>(createdShapes.first())) {
            QMetaObject::invokeMethod(
                KoToolManager::instance(),
                [] {
                    KoToolManager::instance()->switchToolRequested(KoInteractionTool_ID);
                },
                Qt::QueuedConnection);
        }
    }
}

